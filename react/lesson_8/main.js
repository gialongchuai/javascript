// Dom event + react

/**
 * Phần 1:
 * Xử lý Dom events
 * Component do chúng ta định nghĩa phải viết in hoa chữ cái đầu
 * Chọn component trong 1 object
 * Booleans, Null & Undefined không được render
 * Kết hợp giữa toán tử logic để render theo điều kiện
 * 
 * Phần 2:
 * Props trong jsx
 * <YourComponent
 *    propName1 = "String literals"
 *    propName2 = {expression}
 * /> 
 * Props default to "true"
 * Spreadd/Rest props
 * Children prop
 *    <YourComponent>String literals</YourComponent>
 *    <YourComponent>{expression}</YourComponent>
 *  Render props
 */

// UI Component
function Courses({ props, onClick }) {
  return (
    <div>
      <h2 onClick={() => onClick(props.title)}>{props.title}</h2>
      <h3>{props.description}</h3>
      <img src={props.image_url} />
    </div>
  )
}

const Form = { // dù func trong object nó cũng là 1 component render được
  Input() { // enhance object literals
    return <input type="text" name="" id="" />
  },
  Checkbox() {
    return <input type="checkbox" name="" id=""></input>
  }
}

function Button({ // hàm xử lý nếu có href thì chuyển nó thành thẻ a có href
  // còn nếu ko có mặc định là button console log ra 
  title,
  href,
  onClick
}) {
  const props = {};
  let Component = 'button'; // lưu ý trả về thẻ có biến Component viết hoa nhé
  // kẻo nó không nhận á

  if (href) {
    Component = 'a';
    props.href = href;
  }

  if(onClick) {
    props.onClick = onClick;
  }
  // toán tử spread thì phải để lấy ra các object trong props 
  // ví dụ bằng với onClick={onClick}
  return <Component {...props}>{title}</Component>
}

// Container
function App() {

  const handleAlert = (data) => {
    alert(data);
  }

  const type = 'Input';
  const Component = Form[type];

  return (
    <div className="wrapper">
      <Form.Input />
      <Form.Checkbox />
      <Component />
      <br></br>
      <br></br>

      <Button
        title="Click me!"
        // href="https://fullstack.edu.vn/"
        onClick={()=>console.log('Em chào cô giáo Huyền Trang ạ!!!!')}
      />

      <br></br>
      {
        courses.map(course => {
          return (
            <Courses
              onClick={handleAlert}
              props={course}
              key={course.id}
            />
          )

        })
      }
    </div>
  )
}

ReactDOM.render(<App />, document.querySelector('#root'));